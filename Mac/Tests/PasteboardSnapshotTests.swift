import AppKit
import XCTest

/// Uses private, uniquely named pasteboards: the user's clipboard is never read or written.
final class PasteboardSnapshotTests: XCTestCase {
    private var pasteboard: NSPasteboard!

    override func setUp() {
        super.setUp()
        pasteboard = NSPasteboard(name: NSPasteboard.Name("com.geekaz.Scriber.mac.tests.\(UUID().uuidString)"))
    }

    override func tearDown() {
        pasteboard.releaseGlobally()
        pasteboard = nil
        super.tearDown()
    }

    func testRoundTripKeepsEveryItemAndType() {
        let first = NSPasteboardItem()
        first.setString("hello", forType: .string)
        first.setData(Data("<b>hello</b>".utf8), forType: .html)
        first.setData(Data([0x00, 0xFF, 0x10]), forType: NSPasteboard.PasteboardType("com.example.private"))
        let second = NSPasteboardItem()
        second.setString("https://example.com", forType: .URL)
        second.setData(Data(repeating: 7, count: 4096), forType: .png)
        pasteboard.clearContents()
        pasteboard.writeObjects([first, second])

        let snapshot = PasteboardSnapshot.capture(from: pasteboard)
        XCTAssertEqual(snapshot.items.count, 2)
        XCTAssertGreaterThanOrEqual(snapshot.typeCount, 5)

        // Scriber borrows the pasteboard…
        let ours = PasteboardMarkers.writeTemporary("聽寫的文字", to: pasteboard, sourceBundleID: "com.geekaz.Scriber.mac")
        XCTAssertEqual(pasteboard.string(forType: .string), "聽寫的文字")
        XCTAssertTrue(PasteboardMarkers.isTemporary(pasteboard))
        XCTAssertEqual(pasteboard.string(forType: PasteboardMarkers.source), "com.geekaz.Scriber.mac")
        XCTAssertTrue(pasteboard.types?.contains(PasteboardMarkers.concealed) ?? false)
        XCTAssertTrue(pasteboard.types?.contains(PasteboardMarkers.autoGenerated) ?? false)
        XCTAssertTrue(PasteRestorePolicy.shouldRestore(snapshot: snapshot, ourChangeCount: ours,
                                                       currentChangeCount: pasteboard.changeCount))

        // …and gives it back exactly.
        snapshot.restore(to: pasteboard)
        XCTAssertFalse(PasteboardMarkers.isTemporary(pasteboard))
        XCTAssertEqual(PasteboardSnapshot.capture(from: pasteboard), snapshot)
        XCTAssertEqual(pasteboard.string(forType: .string), "hello")
        XCTAssertEqual(pasteboard.pasteboardItems?.count, 2)
        XCTAssertEqual(pasteboard.pasteboardItems?.last?.data(forType: .png), Data(repeating: 7, count: 4096))
    }

    func testEmptyPasteboardIsRestoredAsEmpty() {
        pasteboard.clearContents()
        let snapshot = PasteboardSnapshot.capture(from: pasteboard)
        XCTAssertTrue(snapshot.isEmpty)
        PasteboardMarkers.writeTemporary("text", to: pasteboard, sourceBundleID: nil)
        snapshot.restore(to: pasteboard)
        XCTAssertNil(pasteboard.string(forType: .string))
        XCTAssertEqual(pasteboard.pasteboardItems?.count ?? 0, 0)
    }

    func testSomeoneElseWritingWinsOverTheRestore() {
        pasteboard.clearContents()
        pasteboard.setString("old", forType: .string)
        let snapshot = PasteboardSnapshot.capture(from: pasteboard)
        let ours = PasteboardMarkers.writeTemporary("dictated", to: pasteboard, sourceBundleID: nil)
        // The user copies something before the restore runs.
        pasteboard.clearContents()
        pasteboard.setString("new copy", forType: .string)
        XCTAssertFalse(PasteRestorePolicy.shouldRestore(snapshot: snapshot, ourChangeCount: ours,
                                                        currentChangeCount: pasteboard.changeCount))
        XCTAssertFalse(PasteRestorePolicy.shouldRestore(snapshot: nil, ourChangeCount: ours, currentChangeCount: ours))
    }

    func testRestoreReturnsTheNewChangeCount() {
        pasteboard.clearContents()
        pasteboard.setString("a", forType: .string)
        let snapshot = PasteboardSnapshot.capture(from: pasteboard)
        let count = snapshot.restore(to: pasteboard)
        XCTAssertEqual(count, pasteboard.changeCount)
    }
}

final class HUDFeedbackTests: XCTestCase {
    func testPipelineMessagesMapToShortLabels() {
        XCTAssertEqual(HUDFeedback.forFailure(message: "沒有聽到聲音", retryable: false).label, "沒聽到聲音")
        XCTAssertEqual(HUDFeedback.forFailure(message: "說話時間太短", retryable: false).kind, .benign)
        let offline = HUDFeedback.forFailure(message: "沒有網路連線，請檢查網路後再試", retryable: true)
        XCTAssertEqual(offline.kind, .retry)
        XCTAssertEqual(offline.symbol, HUDFeedback.retrySymbol)
        XCTAssertEqual(offline.label, "沒有網路")
        XCTAssertEqual(HUDFeedback.forFailure(message: "沒有網路連線，請檢查網路後再試", retryable: false).kind, .failure)
        XCTAssertEqual(HUDFeedback.forFailure(message: "API key 無效或沒有權限，請到設定檢查", retryable: false).type,
                       "invalid-key")
        XCTAssertEqual(HUDFeedback.forFailure(message: "還沒設定 Groq 的 API key，請到設定填寫", retryable: false).type,
                       "missing-key")
        XCTAssertEqual(HUDFeedback.forFailure(message: "翻譯需要 Groq 或 Anthropic 的 API key，請到設定填入",
                                              retryable: false).type, "needs-llm-key")
        XCTAssertEqual(HUDFeedback.forFailure(message: "找不到麥克風，請確認輸入裝置", retryable: false).type, "no-input-device")
        XCTAssertEqual(HUDFeedback.forFailure(message: "麥克風中斷了", retryable: false).type, "input-lost")
    }

    func testUnknownMessagesAreNotShownWhole() {
        let long = "某個很長而且沒見過的錯誤訊息，裡面可能有伺服器回傳的內容"
        let feedback = HUDFeedback.forFailure(message: long, retryable: false)
        XCTAssertEqual(feedback.label, "出了點問題")
        XCTAssertEqual(feedback.type, "unknown")
        XCTAssertEqual(HUDFeedback.forFailure(message: long, retryable: true).kind, .retry)
    }

    /// Same rule as the iOS keyboard: icon + at most about six CJK characters, no sentences.
    func testLabelsAreShort() {
        let messages = [
            "已取消", "說話時間太短", "沒有聽到聲音", "沒有辨識到內容，請再說一次",
            "API key 無效或沒有權限，請到設定檢查", "還沒設定 Groq 的 API key，請到設定填寫",
            "翻譯需要 Groq 或 Anthropic 的 API key，請到設定填入", "還沒設定自訂語音辨識的網址，請到設定填寫",
            "帳戶額度不足，請到服務商後台確認", "用量或頻率超過上限，請稍後再試", "沒有網路連線，請檢查網路後再試",
            "連線逾時，請再試一次", "網路連線失敗，請稍後再試", "服務暫時無法使用（503），請稍後再試",
            "找不到指定的模型或服務（404），可能需要更新 App", "錄音檔太大，請說短一點再試", "服務回應錯誤（418）",
            "AI 潤飾拒絕處理這段內容", "AI 潤飾的結果不完整，請再試一次", "找不到麥克風，請確認輸入裝置", "麥克風中斷了",
            "錄音失敗，請再試一次", "無法開始錄音，請再試一次", "處理失敗，請再試一次", "完全沒見過的訊息",
        ]
        var feedbacks = messages.flatMap { [HUDFeedback.forFailure(message: $0, retryable: false),
                                            HUDFeedback.forFailure(message: $0, retryable: true)] }
        feedbacks += [.cancelled, .copiedNoAccessibility(), .copiedSecureInput(appName: "1Password"), .copiedPasteFailed(),
                      .needsMicrophone(), .needsSpeechKey(), .needsLLMKey(for: .edit), .micGranted,
                      .translateOn(languageName: "英文")]
        for feedback in feedbacks {
            let cjk = feedback.label.unicodeScalars.filter { $0.value >= 0x2E80 && $0.value <= 0x9FFF }.count
            XCTAssertLessThanOrEqual(cjk, 6, "\(feedback.type): \(feedback.label)")
            XCTAssertFalse(feedback.label.contains("，"), feedback.label)
        }
    }

    func testSameCasesUseTheIOSLabels() {
        XCTAssertEqual(HUDFeedback.forFailure(message: "沒有聽到聲音", retryable: false).label, "沒聽到聲音")
        XCTAssertEqual(HUDFeedback.forFailure(message: "說話時間太短", retryable: false).label, "太短了")
        XCTAssertEqual(HUDFeedback.forFailure(message: "連線逾時，請再試一次", retryable: false).label, "連線逾時")
        XCTAssertEqual(HUDFeedback.forFailure(message: "翻譯需要 Groq 或 Anthropic 的 API key，請到設定填入",
                                              retryable: false).label, "需要 API key")
        XCTAssertEqual(HUDFeedback.needsMicrophone().label, "需要麥克風")
        XCTAssertEqual(HUDFeedback.forFailure(message: "沒有聽到聲音", retryable: false).duration, 1.7)
        XCTAssertEqual(HUDFeedback.forFailure(message: "網路連線失敗，請稍後再試", retryable: true).duration, 2.6)
    }

    func testDurations() {
        XCTAssertLessThan(HUDFeedback.cancelled.duration, HUDFeedback.copiedNoAccessibility().duration)
        XCTAssertTrue(HUDFeedback.copiedSecureInput(appName: "1Password").message.contains("「1Password」"))
        XCTAssertFalse(HUDFeedback.cancelled.isProblem)
        XCTAssertTrue(HUDFeedback.needsMicrophone().isProblem)
    }
}
