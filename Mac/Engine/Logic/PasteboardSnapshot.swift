import AppKit

/// Everything on a pasteboard, every item and every type, as plain data, so it can be put back
/// after Scriber borrows the pasteboard to paste (or to copy a selection).
struct PasteboardSnapshot: Equatable {
    struct Entry: Equatable {
        var type: String
        var data: Data
    }

    struct Item: Equatable {
        var entries: [Entry]
    }

    var items: [Item]

    var isEmpty: Bool { items.isEmpty }
    var typeCount: Int { items.reduce(0) { $0 + $1.entries.count } }
    var byteCount: Int { items.reduce(0) { $0 + $1.entries.reduce(0) { $0 + $1.data.count } } }

    /// Reads every type of every item. Types whose data cannot be read are skipped.
    ///
    /// On the general pasteboard this is a programmatic read: macOS 15.4+ may ask the user
    /// (「允許從其他 App 貼上」) unless Scriber is allowed in Privacy & Security.
    static func capture(from pasteboard: NSPasteboard) -> PasteboardSnapshot {
        let items: [Item] = (pasteboard.pasteboardItems ?? []).compactMap { item in
            let entries = item.types.compactMap { type -> Entry? in
                guard let data = item.data(forType: type) else { return nil }
                return Entry(type: type.rawValue, data: data)
            }
            return entries.isEmpty ? nil : Item(entries: entries)
        }
        return PasteboardSnapshot(items: items)
    }

    /// Replaces the pasteboard's contents with the snapshot (an empty snapshot clears it).
    /// Returns the pasteboard's new change count.
    @discardableResult
    func restore(to pasteboard: NSPasteboard) -> Int {
        pasteboard.clearContents()
        let objects: [NSPasteboardItem] = items.map { item in
            let object = NSPasteboardItem()
            for entry in item.entries {
                object.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type))
            }
            return object
        }
        if !objects.isEmpty { pasteboard.writeObjects(objects) }
        return pasteboard.changeCount
    }
}

/// The nspasteboard.org conventions clipboard managers honour.
enum PasteboardMarkers {
    /// "Temporary, do not record."
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    /// "Sensitive, do not show or keep."
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    /// "Put there by an app, not by the user."
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    /// Bundle id of the app that wrote it.
    static let source = NSPasteboard.PasteboardType("org.nspasteboard.source")

    static let all: [NSPasteboard.PasteboardType] = [transient, concealed, autoGenerated]

    /// Puts `text` on the pasteboard as a temporary item that clipboard managers should ignore.
    /// Returns the pasteboard's change count after the write.
    @discardableResult
    static func writeTemporary(_ text: String, to pasteboard: NSPasteboard, sourceBundleID: String?) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for marker in all { item.setData(Data(), forType: marker) }
        if let sourceBundleID { item.setString(sourceBundleID, forType: source) }
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// Whether the pasteboard's first item carries the transient marker.
    static func isTemporary(_ pasteboard: NSPasteboard) -> Bool {
        pasteboard.pasteboardItems?.first?.types.contains(transient) ?? false
    }
}

/// When the borrowed pasteboard is given back.
enum PasteRestorePolicy {
    /// How long the target app gets to read the pasted text before the old contents come back.
    /// ⌘V is handled asynchronously by the target; Electron apps can take a few hundred ms.
    static let restoreDelay: TimeInterval = 0.6
    /// ⌘C fallback: how long to wait for the target to put the selection on the pasteboard.
    static let copyTimeout: TimeInterval = 0.6
    static let copyPollInterval: TimeInterval = 0.02

    /// Restore only if there is something to restore and nobody wrote to the pasteboard since our
    /// temporary item (the user or another app copying something must win).
    static func shouldRestore(snapshot: PasteboardSnapshot?, ourChangeCount: Int, currentChangeCount: Int) -> Bool {
        snapshot != nil && currentChangeCount == ourChangeCount
    }
}
